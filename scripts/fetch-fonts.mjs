// Downloads the latin woff2 subsets from Google Fonts and writes
// public/fonts.css + public/fonts/*.woff2 so the deployed site makes no
// third-party font requests at runtime.
//
// Both families are served as variable fonts: every requested weight points at
// the same file, so we keep one file per family and declare a weight range.
import { mkdir, rm, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";

const UA =
  "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/126.0 Safari/537.36";

const FAMILIES = ["Inter+Tight:wght@500;600;700", "Inter:wght@400;500;600"];

const url =
  "https://fonts.googleapis.com/css2?" +
  FAMILIES.map((f) => `family=${f}`).join("&") +
  "&display=swap";

const res = await fetch(url, { headers: { "User-Agent": UA } });
if (!res.ok) throw new Error(`Google Fonts responded ${res.status}`);
const css = await res.text();

await mkdir("public/fonts", { recursive: true });

const seen = new Map(); // src url -> { family, file }
const byFamily = new Map(); // family -> { file, weights:Set }

for (const block of css.split("@font-face").slice(1)) {
  const subset = /\/\*\s*([a-z0-9-\[\]]+)\s*\*\//.exec(block)?.[1];
  if (subset !== "latin") continue;

  const family = /font-family:\s*'([^']+)'/.exec(block)?.[1];
  const weight = /font-weight:\s*([0-9]+)/.exec(block)?.[1];
  const src = /url\((https:\/\/[^)]+\.woff2)\)/.exec(block)?.[1];
  if (!family || !weight || !src) continue;

  const slug = family.toLowerCase().replace(/\s+/g, "-");

  if (!seen.has(src)) {
    const buf = Buffer.from(
      await (await fetch(src, { headers: { "User-Agent": UA } })).arrayBuffer(),
    );
    const hash = createHash("md5").update(buf).digest("hex").slice(0, 8);
    const file = `${slug}-latin-${hash}.woff2`;
    await writeFile(`public/fonts/${file}`, buf);
    console.log(`${file}  ${(buf.length / 1024).toFixed(1)} KB  (${family})`);
    seen.set(src, { family, file });
  }

  const entry = seen.get(src);
  if (!byFamily.has(family)) byFamily.set(family, { file: entry.file, weights: new Set() });
  byFamily.get(family).weights.add(Number(weight));
}

if (byFamily.size === 0) throw new Error("no latin faces parsed - the CSS shape changed");

const faces = [...byFamily].map(([family, { file, weights }]) => {
  const sorted = [...weights].sort((a, b) => a - b);
  // The file is a variable font covering every requested weight.
  const range = `${sorted[0]} ${Math.max(sorted[sorted.length - 1], 900)}`;
  return (
    `@font-face{font-family:'${family}';font-style:normal;font-weight:${range};` +
    `font-display:swap;src:url('./fonts/${file}') format('woff2');}`
  );
});

await writeFile(
  "public/fonts.css",
  "/* Generated by scripts/fetch-fonts.mjs - self-hosted latin variable subsets. */\n" +
    faces.join("\n") +
    "\n",
);

// Drop any stale per-weight files from earlier runs.
const keep = new Set([...seen.values()].map((v) => v.file));
const { readdir } = await import("node:fs/promises");
for (const f of await readdir("public/fonts")) {
  if (f.endsWith(".woff2") && !keep.has(f)) {
    await rm(`public/fonts/${f}`);
    console.log(`removed stale ${f}`);
  }
}

console.log(`\nwrote public/fonts.css with ${faces.length} @font-face rules`);
